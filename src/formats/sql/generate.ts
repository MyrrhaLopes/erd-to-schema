import type { Column, Project, Relationship, SchemaModel, Table } from '../../model/types';
import { formatType } from '../../model/columnType';
import { qi, sqlString } from '../../model/naming';
import { columnById, tableById } from '../../model/schema';
import { directiveLines } from '../common';

const qualified = (t: { name: string; schema?: string }) => (t.schema ? qi(t.schema) + '.' : '') + qi(t.name);

const colNames = (t: Table, ids: string[]) => ids.map((id) => qi(columnById(t, id)?.name ?? '?')).join(', ');

export function defaultFkName(schema: SchemaModel, r: Relationship) {
  const t = tableById(schema, r.fromTable)!;
  return `${t.name}_${r.fromColumns.map((c) => columnById(t, c)?.name).join('_')}_fkey`;
}

export function defaultIndexName(t: Table, cols: string[], unique: boolean) {
  return `${t.name}_${cols.map((c) => columnById(t, c)?.name).join('_')}_${unique ? 'key' : 'idx'}`;
}

/** Linha de definição de uma coluna (também usada como assinatura na reconciliação) */
export function columnSql(col: Column, table: Table): string {
  const singlePk = table.primaryKey.length === 1 && table.primaryKey[0] === col.id && !table.primaryKeyName;
  const inPk = table.primaryKey.includes(col.id);
  let s = `${qi(col.name)} ${formatType(col.type, qi)}`;
  if (col.identity) s += col.identity === 'always' ? ' GENERATED ALWAYS AS IDENTITY' : ' GENERATED BY DEFAULT AS IDENTITY';
  if (singlePk) s += ' PRIMARY KEY';
  else if (!col.nullable && !inPk) s += ' NOT NULL';
  if (col.unique && !singlePk) s += ' UNIQUE';
  if (col.default !== undefined && col.default !== '') s += ` DEFAULT ${col.default}`;
  return s;
}

export function tableSql(t: Table): string {
  const lines = t.columns.map((c) => '  ' + columnSql(c, t));
  const singlePk = t.primaryKey.length === 1 && !t.primaryKeyName;
  if (t.primaryKey.length && !singlePk) {
    lines.push(`  ${t.primaryKeyName ? `CONSTRAINT ${qi(t.primaryKeyName)} ` : ''}PRIMARY KEY (${colNames(t, t.primaryKey)})`);
  }
  for (const u of t.uniques) lines.push(`  ${u.name ? `CONSTRAINT ${qi(u.name)} ` : ''}UNIQUE (${colNames(t, u.columns)})`);
  for (const c of t.checks) lines.push(`  ${c.name ? `CONSTRAINT ${qi(c.name)} ` : ''}CHECK (${c.expr})`);
  return `CREATE TABLE ${qualified(t)} (\n${lines.join(',\n')}\n);`;
}

export function fkSql(schema: SchemaModel, r: Relationship): string {
  const from = tableById(schema, r.fromTable)!;
  const to = tableById(schema, r.toTable)!;
  let s =
    `ALTER TABLE ${qualified(from)} ADD CONSTRAINT ${qi(r.name ?? defaultFkName(schema, r))}\n` +
    `  FOREIGN KEY (${colNames(from, r.fromColumns)}) REFERENCES ${qualified(to)} (${colNames(to, r.toColumns)})`;
  if (r.onDelete && r.onDelete !== 'no action') s += ` ON DELETE ${r.onDelete.toUpperCase()}`;
  if (r.onUpdate && r.onUpdate !== 'no action') s += ` ON UPDATE ${r.onUpdate.toUpperCase()}`;
  return s + ';';
}

export function generateSql(project: Pick<Project, 'schema' | 'meta'>): string {
  const { schema } = project;
  const out: string[] = [];
  const schemas = new Set([...schema.tables, ...schema.enums].map((t) => t.schema).filter((s): s is string => !!s && s !== 'public'));
  for (const s of schemas) out.push(`CREATE SCHEMA IF NOT EXISTS ${qi(s)};`);
  for (const e of schema.enums) out.push(`CREATE TYPE ${qualified(e)} AS ENUM (${e.values.map(sqlString).join(', ')});`);
  for (const t of schema.tables) out.push(tableSql(t));

  // FKs agrupadas pela ordem das tabelas: a ordem interna das relações não é semântica
  const order = new Map(schema.tables.map((t, i) => [t.id, i]));
  const fks = schema.relationships
    .filter((r) => r.kind === 'fk' && tableById(schema, r.fromTable) && tableById(schema, r.toTable))
    .map((r, i) => ({ r, i }))
    .sort((a, b) => order.get(a.r.fromTable)! - order.get(b.r.fromTable)! || a.i - b.i)
    .map((x) => x.r);
  for (const r of fks) out.push(fkSql(schema, r));

  for (const t of schema.tables) {
    for (const i of t.indexes) {
      let s = `CREATE ${i.unique ? 'UNIQUE ' : ''}INDEX ${qi(i.name ?? defaultIndexName(t, i.columns, i.unique))} ON ${qualified(t)}`;
      if (i.method && i.method !== 'btree') s += ` USING ${i.method}`;
      s += ` (${colNames(t, i.columns)})`;
      if (i.where) s += ` WHERE ${i.where}`;
      out.push(s + ';');
    }
  }

  const comments: string[] = [];
  for (const t of schema.tables) {
    if (t.comment) comments.push(`COMMENT ON TABLE ${qualified(t)} IS ${sqlString(t.comment)};`);
    for (const c of t.columns) if (c.comment) comments.push(`COMMENT ON COLUMN ${qualified(t)}.${qi(c.name)} IS ${sqlString(c.comment)};`);
  }
  if (comments.length) out.push(comments.join('\n'));

  const directives = directiveLines(project as Project, 'sql');
  if (directives.length) out.push('-- Conceitos do canvas (relações-nota e tags)\n' + directives.join('\n'));

  return out.join('\n\n') + (out.length ? '\n' : '');
}
