import { describe, expect, it } from 'vitest';
import { generatePrisma, prismaColumnSignature } from '../src/formats/prisma/generate';
import { parsePrisma } from '../src/formats/prisma/parse';
import { columnSql, generateSql } from '../src/formats/sql/generate';
import { reconcile } from '../src/reconcile';
import { emptyProject, sql } from './helpers';

const prisma = (text: string) => {
  const r = parsePrisma(text);
  if (!r.ok) throw new Error(r.diagnostics.map((d) => d.message).join('\n'));
  return r.parsed;
};

const SCHEMA = `
datasource db {
  provider = "postgresql"
  url      = env("DATABASE_URL")
}

enum Role {
  ADMIN
  USER
  @@map("role")
}

/// Usuários do sistema
model User {
  id        Int      @id @default(autoincrement())
  email     String   @unique @db.VarChar(255) /// login
  firstName String?  @map("first_name")
  role      Role     @default(USER)
  createdAt DateTime @default(now()) @map("created_at")
  posts     Post[]
  @@map("users")
}

model Post {
  id       Int    @id @default(autoincrement())
  authorId Int    @map("author_id")
  author   User   @relation(fields: [authorId], references: [id], onDelete: Cascade)
  tags     Tag[]
  @@index([authorId])
  @@map("posts")
}

model Tag {
  id    Int    @id @default(autoincrement())
  name  String
  posts Post[]
  @@map("tags")
}
`;

describe('Prisma', () => {
  it('parses models, relations, enums and implicit m:n', () => {
    const p = prisma(SCHEMA);
    expect(p.schema.tables.map((t) => t.name)).toEqual(['users', 'posts', 'tags', '_PostToTag']);
    const users = p.schema.tables[0];
    expect(users.comment).toBe('Usuários do sistema');
    expect(users.columns.map((c) => c.name)).toEqual(['id', 'email', 'first_name', 'role', 'created_at']);
    expect(users.columns[0].type.base).toBe('serial');
    expect(users.columns[1]).toMatchObject({ type: { base: 'varchar', args: [255] }, unique: true, comment: 'login' });
    expect(users.columns[3]).toMatchObject({ type: { base: 'role' }, default: "'USER'::role" });
    expect(users.columns[4]).toMatchObject({ type: { base: 'timestamp', args: [3] }, default: 'now()' });
    const fk = p.schema.relationships.find((r) => r.fromTable === p.schema.tables[1].id)!;
    expect(fk.onDelete).toBe('cascade');
    const pivot = p.schema.tables[3];
    expect(p.meta[pivot.id].provenance).toMatchObject({ kind: 'pivot', implicit: 'prisma' });
    expect(pivot.columns.map((c) => c.name)).toEqual(['A', 'B']);
  });

  it('round-trips prisma → model → prisma', () => {
    const p1 = prisma(SCHEMA);
    const base = reconcile(emptyProject(), p1, 'prisma', prismaColumnSignature);
    const text = generatePrisma(base);
    const p2 = prisma(text);
    const r = reconcile(base, p2, 'prisma', prismaColumnSignature);
    expect(r.changes).toEqual([]);
    expect(generatePrisma(r)).toBe(text);
    expect(text).toContain('tags     Tag[]');
    expect(text).not.toContain('model PostToTag');
  });

  it('relationship comments become /// on the relation field', async () => {
    const s = await sql(`
      CREATE TABLE users (id serial PRIMARY KEY);
      CREATE TABLE posts (id serial PRIMARY KEY, author_id int NOT NULL REFERENCES users);
      COMMENT ON CONSTRAINT posts_author_id_fkey ON posts IS E'autor do post\\nobrigatório';`);
    const base = reconcile(emptyProject(), s, 'sql', columnSql);
    const text = generatePrisma(base);
    expect(text).toContain('  /// autor do post\n  /// obrigatório\n  author');
    const r = reconcile(base, prisma(text), 'prisma', prismaColumnSignature);
    expect(r.changes).toEqual([]);
    expect(r.schema.relationships[0].comment).toBe('autor do post\nobrigatório');
    expect(generateSql(r)).toBe(generateSql(base));
    const edited = reconcile(base, prisma(text.replace('/// obrigatório', '/// opcional')), 'prisma', prismaColumnSignature);
    expect(edited.schema.relationships[0].comment).toBe('autor do post\nopcional');
  });

  it('keeps CHECK constraints and partial indexes after editing prisma', async () => {
    const s = await sql(`
      CREATE TABLE users (id serial PRIMARY KEY, age int NOT NULL, email text, CHECK (age >= 0));
      CREATE UNIQUE INDEX users_email_key ON users (email) WHERE email IS NOT NULL;
      COMMENT ON TABLE users IS 'u';`);
    const base = reconcile(emptyProject(), s, 'sql', columnSql);
    const ptext = generatePrisma(base).replace('age   Int', 'years Int @map("age")\n  nick  String?');
    const p = prisma(ptext);
    const r = reconcile(base, p, 'prisma', prismaColumnSignature);
    const out = generateSql(r);
    expect(out).toContain('CHECK (age >= 0)');
    expect(out).toContain('WHERE email IS NOT NULL');
    expect(out).toContain('nick text');
    expect(r.schema.tables[0].id).toBe(base.schema.tables[0].id);
  });

  it('SQL → Prisma → SQL keeps serial/identity and defaults', async () => {
    const s = await sql(`
      CREATE TABLE a (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, created timestamptz DEFAULT CURRENT_TIMESTAMP, u uuid DEFAULT gen_random_uuid() NOT NULL);
      CREATE TABLE b (id bigserial PRIMARY KEY, a_id int REFERENCES a(id) ON DELETE SET NULL);`);
    const base = reconcile(emptyProject(), s, 'sql', columnSql);
    const sql1 = generateSql(base);
    const p = prisma(generatePrisma(base));
    const r = reconcile(base, p, 'prisma', prismaColumnSignature);
    expect(generateSql(r)).toBe(sql1);
  });

  it('reports syntax errors', () => {
    const r = parsePrisma('model A {\n  id Int @id\n  name String @@\n}');
    expect(r.ok).toBe(false);
  });
});
