import { chromium } from 'playwright';
import { existsSync } from 'node:fs';
const executablePath = process.env.CHROMIUM ?? (existsSync('/opt/pw-browsers/chromium') ? '/opt/pw-browsers/chromium' : undefined);
const url = process.env.URL ?? 'http://localhost:5173/';
const out = process.env.OUT ?? '.';
const browser = await chromium.launch({ executablePath });
const page = await browser.newPage({ viewport: { width: 1600, height: 950 } });
const logs = [];
page.on('console', (m) => logs.push(`[${m.type()}] ${m.text()}`));
page.on('pageerror', (e) => logs.push(`[pageerror] ${e.message}`));
await page.goto(url);
await page.waitForSelector('.react-flow__node-table', { timeout: 20000 }).catch(() => {});
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/01-loaded.png` });
console.log('tables:', await page.locator('.react-flow__node-table').count());
console.log('edges:', await page.locator('.react-flow__edge').count());
console.log(logs.join('\n'));
await browser.close();
